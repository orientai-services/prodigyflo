export function iconByName(name: string): LucideIcon | undefined {
  return Object.hasOwn(ICONS_BY_NAME, name) ? ICONS_BY_NAME[name] : undefined
}

/** The icon called `name`, else `fallback`. */
export function NamedIcon({ name, fallback, className }: { name: string; fallback: LucideIcon; className?: string }) {
  return createElement(iconByName(name) ?? fallback, { className })
}
