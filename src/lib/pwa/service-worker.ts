/**
 * Source of the app-shell service worker served at `/sw.js` (scope `/`) by
 * src/app/sw.js/route.ts. Kept as a string builder so the version can be
 * stamped per deployment: a byte-different worker is what makes the browser
 * install it, and the install is what tells an open app "new version, reload".
 *
 * What it does, and deliberately does not do (docs/MOBILE.md "Installed app"):
 *
 * - PAGES (navigations): network first, always. The offline page answers only
 *   when the network is unreachable. Authenticated HTML is never stored, so a
 *   signed-out device never shows yesterday's leads.
 * - HASHED BUILD ASSETS (/_next/static) and the brand/PWA images: cache first.
 *   Their names change when their content does, so a cached copy is never
 *   stale; keeping old ones also lets an app that was open across a deploy
 *   finish loading its old chunks.
 * - EVERYTHING ELSE (API, server actions, RSC fetches, recordings, uploads,
 *   other origins, non-GET): not touched, the browser handles it as if there
 *   were no worker.
 * - PUSH: none here. Team chat's push worker (public/chat-sw.js) owns the
 *   narrower scope /chat-sw/ and keeps its own subscription; the two never
 *   meet.
 */
export const OFFLINE_URL = '/offline.html'

/** Hashed asset cache cap; oldest entries go first. */
export const STATIC_CACHE_MAX = 600

export function serviceWorkerSource(version: string): string {
  const v = JSON.stringify(String(version).replace(/[^A-Za-z0-9._-]/g, '').slice(0, 40) || 'dev')
  return `// ProdigyFlo app shell worker. Generated by src/lib/pwa/service-worker.ts; do not edit the served file.
'use strict'
const VERSION = ${v}
const SHELL_CACHE = 'pf-shell-' + VERSION
const STATIC_CACHE = 'pf-static-v1'
const OFFLINE_URL = ${JSON.stringify(OFFLINE_URL)}
const STATIC_MAX = ${STATIC_CACHE_MAX}
const SHELL = [OFFLINE_URL, '/brand/prodigyflo/icon-192.png']

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(SHELL_CACHE)
      .then((cache) => cache.addAll(SHELL.map((url) => new Request(url, { cache: 'reload' }))))
      .then(() => self.skipWaiting()),
  )
})

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const keep = new Set([SHELL_CACHE, STATIC_CACHE])
    for (const key of await caches.keys()) {
      if (key.startsWith('pf-') && !keep.has(key)) await caches.delete(key)
    }
    if (self.registration.navigationPreload) {
      try { await self.registration.navigationPreload.enable() } catch (e) { /* not supported */ }
    }
    await self.clients.claim()
  })())
})

self.addEventListener('message', (event) => {
  if (event.data && event.data.type === 'SKIP_WAITING') self.skipWaiting()
})

function isStatic(url) {
  return url.pathname.startsWith('/_next/static/') ||
    /^\\/(brand|pwa|splash)\\//.test(url.pathname)
}

async function offline() {
  const hit = await caches.match(OFFLINE_URL, { ignoreSearch: true })
  return hit || new Response('You are offline.', { status: 503, headers: { 'content-type': 'text/plain; charset=utf-8' } })
}

async function page(event) {
  try {
    const preloaded = await event.preloadResponse
    if (preloaded) return preloaded
    return await fetch(event.request)
  } catch (e) {
    return offline()
  }
}

async function trim(cache) {
  const keys = await cache.keys()
  for (let i = 0; i < keys.length - STATIC_MAX; i++) await cache.delete(keys[i])
}

async function asset(event) {
  const cache = await caches.open(STATIC_CACHE)
  const hit = await cache.match(event.request)
  if (hit) return hit
  const response = await fetch(event.request)
  if (response.ok && response.type === 'basic') {
    const copy = response.clone()
    event.waitUntil(cache.put(event.request, copy).then(() => trim(cache)).catch(() => {}))
  }
  return response
}

self.addEventListener('fetch', (event) => {
  const request = event.request
  if (request.method !== 'GET') return
  const url = new URL(request.url)
  if (url.origin !== self.location.origin) return
  if (request.mode === 'navigate') {
    event.respondWith(page(event))
    return
  }
  if (isStatic(url) && !request.headers.has('range')) event.respondWith(asset(event))
})
`
}
